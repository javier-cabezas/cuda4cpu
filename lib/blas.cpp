//! x = op(A) x
template <typename T>
void trmv_builtin(triangle<const T> A, op trans, diag d, vec<T> x)
{
    const int n = A.n;
    const int w = A.width();
    const bool upper = A.upper_after(trans);
    std::vector<T> out(n);
    for (int i = 0; i < n; ++i) {
        T s = 0;
        const int j0 = upper ? i : std::max(0, i - w);
        const int j1 = upper ? std::min(n - 1, i + w) : i;
        for (int j = j0; j <= j1; ++j)
            s += A.tri(i, j, trans, d) * x[j];
        out[i] = s;
    }
    for (int i = 0; i < n; ++i)
        x[i] = out[i];
}

//! Solves op(A) x = b, b in x
template <typename T>
void trsv_builtin(triangle<const T> A, op trans, diag d, vec<T> x)
{
    const int n = A.n;
    const int w = A.width();
    if (A.upper_after(trans)) {
        for (int i = n - 1; i >= 0; --i) {
            T s = x[i];
            for (int j = i + 1; j <= std::min(n - 1, i + w); ++j)
                s -= A.tri(i, j, trans, d) * x[j];
            x[i] = d == diag::unit ? s : s / A.tri(i, i, trans, d);
        }
    } else {
        for (int i = 0; i < n; ++i) {
            T s = x[i];
            for (int j = std::max(0, i - w); j < i; ++j)
                s -= A.tri(i, j, trans, d) * x[j];
            x[i] = d == diag::unit ? s : s / A.tri(i, i, trans, d);
        }
    }
}

template <typename T>
status triangular_vector(const context &c, fill uplo, op trans, diag d, int n, int k, layout lay, const T *A,
                         int lda, T *x, int incx, bool solve)
{
    if (!valid(uplo) || !valid(trans) || !valid(d))
        return status::invalid_value;
    if (n < 0 || k < 0 || incx == 0 || (lay == layout::dense && lda < max1(n)) || (lay == layout::band && lda < k + 1))
        return status::invalid_size;
    return run(c, [=] {
        if (n == 0)
            return;
        if (lay == layout::dense) {
            using F = void(int, int, int, int, int, cb_in<T>, int, cb_out<T>, int);
            if (auto f = solve ? cblas_function<F, T, "", "trsv">() : cblas_function<F, T, "", "trmv">()) {
                f(col_major, cb(uplo), cb(trans), cb(d), n, A, lda, x, incx);
                return;
            }
        }
        const triangle<const T> tri{A, lda, k, n, uplo, lay};
        if (solve)
            trsv_builtin(tri, trans, d, v(x, n, incx));
        else
            trmv_builtin(tri, trans, d, v(x, n, incx));
    });
}

