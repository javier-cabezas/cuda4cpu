//! Runs f now, or as a host node of the graph that the stream is capturing,
//! which owns f (and so do the executable graphs made from it)
template <typename F>
status run(const context &c, F &&f)
{
    if (capturing(c.stream)) {
        auto job = std::make_shared<std::function<void()>>(std::forward<F>(f));
        auto call = [](void *data) { (*static_cast<std::function<void()> *>(data))(); };
        return capture_host_owned(c.stream, call, job) == cudaSuccess ? status::success : status::execution_failed;
    }
    f();
    return status::success;
}

// The CBLAS library

struct cblas_library {
    void *handle = nullptr;
    std::string name;
};

//! A library with the CBLAS of every type (cblas_sgemm ... cblas_zgemm)
inline void *open_cblas(const char *name)
{
    void *handle = dlopen(name, RTLD_NOW | RTLD_LOCAL);
    if (handle == nullptr)
        return nullptr;
    for (const char *symbol : {"cblas_sgemm", "cblas_dgemm", "cblas_cgemm", "cblas_zgemm"}) {
        if (dlsym(handle, symbol) == nullptr) {
            dlclose(handle);
            return nullptr;
        }
    }
    return handle;
}

//! CUDA4CPU_BLAS names the library (a path, or a name the dynamic loader
//! finds), or builtin for cuda4cpu's own BLAS. Without it, the first of the
//! usual libraries that loads.
inline const cblas_library &cblas()
{
    static const cblas_library library = [] {
        cblas_library l;
        const char *setting = std::getenv("CUDA4CPU_BLAS");
        if (setting != nullptr && *setting != '\0') {
            if (std::string_view(setting) == "builtin")
                return l;
            l.handle = open_cblas(setting);
            if (l.handle == nullptr)
                std::fprintf(stderr,
                             "cuda4cpu: warning: CUDA4CPU_BLAS=%s isn't a CBLAS library that can be loaded "
                             "(cblas_sgemm ... cblas_zgemm): cuda4cpu's own BLAS runs instead.\n",
                             setting);
            else
                l.name = setting;
            return l;
        }
        for (const char *name : {"libopenblas.so.0", "libopenblas.so", "libblis.so.4", "libblis.so", "libmkl_rt.so.2",
                                 "libmkl_rt.so", "libcblas.so.3", "libblas.so.3"}) {
            if ((l.handle = open_cblas(name)) != nullptr) {
                l.name = name;
                break;
            }
        }
        return l;
    }();
    return library;
}

template <typename T> constexpr char letter = 0;
template <> constexpr char letter<float> = 's';
template <> constexpr char letter<double> = 'd';
template <> constexpr char letter<cf> = 'c';
template <> constexpr char letter<cd> = 'z';

template <std::size_t N>
struct fixed_string {
    char text[N];
    constexpr fixed_string(const char (&s)[N]) { std::copy_n(s, N, text); }
};

//! CBLAS's function cblas_<prefix><letter of T><suffix> (cblas_sgemm,
//! cblas_scnrm2, cblas_icamax, ...), or nullptr
template <typename F, typename T, fixed_string Prefix, fixed_string Suffix>
F *cblas_function()
{
    static F *const function = [] {
        const cblas_library &l = cblas();
        if (l.handle == nullptr)
            return static_cast<F *>(nullptr);
        std::string symbol = std::string("cblas_") + Prefix.text + letter<T> + Suffix.text;
        return reinterpret_cast<F *>(dlsym(l.handle, symbol.c_str()));
    }();
    return function;
}

// CBLAS's argument types: real scalars by value, complex ones and complex
// arrays through void pointers
template <typename T> using cb_value = std::conditional_t<is_complex<T>, const void *, T>;
template <typename T> using cb_in = std::conditional_t<is_complex<T>, const void *, const T *>;
template <typename T> using cb_out = std::conditional_t<is_complex<T>, void *, T *>;

template <typename T>
cb_value<T> value_arg(const T &v)
{
    if constexpr (is_complex<T>)
        return &v;
    else
        return v;
}

enum cblas_enum : int {
    col_major = 102,
    no_trans = 111, trans = 112, conj_trans = 113,
    upper = 121, lower = 122,
    non_unit = 131, unit = 132,
    left = 141, right = 142
};

inline int cb(op o) { return o == op::n ? no_trans : o == op::t ? trans : conj_trans; }
inline int cb(fill f) { return f == fill::upper ? upper : lower; }
inline int cb(diag d) { return d == diag::unit ? unit : non_unit; }
inline int cb(side s) { return s == side::left ? left : right; }

// Strided vectors, as the BLAS indexes them: a negative increment starts at
// the end

template <typename T>
struct vec {
    T *p;
    int n;
    int inc;

    T &operator[](int k) const
    {
        const std::ptrdiff_t i = inc >= 0 ? std::ptrdiff_t(k) * inc : (std::ptrdiff_t(k) - (n - 1)) * inc;
        return p[i];
    }
};

template <typename T>
vec<T> v(T *p, int n, int inc)
{
    return {p, n, inc};
}

//! Whether to split work across OpenMP's threads: not in a parallel region
//! (the program's, or a batch's), and enough of it
inline bool parallel_for(double work)
{
    return work > 32768 && !omp_in_parallel();
}

inline int max1(int v) { return std::max(1, v); }

