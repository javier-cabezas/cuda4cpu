inline status check_triangular_matrix(side sd, fill uplo, op trans, diag d, int m, int n, int lda, int ldb)
{
    if (!valid(sd) || !valid(uplo) || !valid(trans) || !valid(d))
        return status::invalid_value;
    if (m < 0 || n < 0 || lda < max1(sd == side::left ? m : n) || ldb < max1(m))
        return status::invalid_size;
    return status::success;
}

//! C = alpha op(A) B (left) or alpha B op(A) (right), A triangular; C may
//! be B
template <typename T>
void trmm_builtin(side sd, fill uplo, op trans, diag d, int m, int n, T alpha, const T *A, int lda, const T *B,
                  int ldb, T *C, int ldc)
{
    const int ka = sd == side::left ? m : n;
    const triangle<const T> tri{A, lda, 0, ka, uplo, layout::dense};
    if (sd == side::left) {
#pragma omp parallel for schedule(static) if (parallel_for(double(m) * m * n / 2))
        for (int j = 0; j < n; ++j) {
            std::vector<T> column(B + std::ptrdiff_t(j) * ldb, B + std::ptrdiff_t(j) * ldb + m);
            trmv_builtin(tri, trans, d, v(column.data(), m, 1));
            for (int i = 0; i < m; ++i)
                C[i + std::ptrdiff_t(j) * ldc] = alpha * column[i];
        }
    } else {
        const bool upper = tri.upper_after(trans);
#pragma omp parallel for schedule(static) if (parallel_for(double(m) * n * n / 2))
        for (int i = 0; i < m; ++i) {
            std::vector<T> row(n);
            for (int l = 0; l < n; ++l)
                row[l] = B[i + std::ptrdiff_t(l) * ldb];
            for (int j = 0; j < n; ++j) {
                T s = 0;
                const int l0 = upper ? 0 : j;
                const int l1 = upper ? j : n - 1;
                for (int l = l0; l <= l1; ++l)
                    s += row[l] * tri.tri(l, j, trans, d);
                C[i + std::ptrdiff_t(j) * ldc] = alpha * s;
            }
        }
    }
}

template <typename T>
status trmm(const context &c, side sd, fill uplo, op trans, diag d, int m, int n, scalar<T> alpha, const T *A,
            int lda, const T *B, int ldb, T *C, int ldc)
{
    if (alpha.missing)
        return status::invalid_value;
    if (status s = check_triangular_matrix(sd, uplo, trans, d, m, n, lda, ldb); s != status::success)
        return s;
    if (ldc < max1(m))
        return status::invalid_size;
    return run(c, [=] {
        if (m == 0 || n == 0)
            return;
        const T a = alpha.get();
        using F = void(int, int, int, int, int, int, int, cb_value<T>, cb_in<T>, int, cb_out<T>, int);
        if (auto f = cblas_function<F, T, "", "trmm">()) {
            // CBLAS's is in place: B's copy in C first
            if (C != B)
                for (int j = 0; j < n; ++j)
                    std::copy_n(B + std::ptrdiff_t(j) * ldb, m, C + std::ptrdiff_t(j) * ldc);
            f(col_major, cb(sd), cb(uplo), cb(trans), cb(d), m, n, value_arg(a), A, lda, C, ldc);
            return;
        }
        trmm_builtin(sd, uplo, trans, d, m, n, a, A, lda, B, ldb, C, ldc);
    });
}

//! Solves op(A) X = alpha B (left) or X op(A) = alpha B (right), X in B: a
//! row x of X op(A) = b solves op(A)^T x^T = b^T, and op(A)^T is A^T, A, or
//! A's conjugate
template <typename T>
void trsm_builtin(side sd, fill uplo, op trans, diag d, int m, int n, T alpha, const T *A, int lda, T *B, int ldb)
{
    if (sd == side::left) {
        const triangle<const T> tri{A, lda, 0, m, uplo, layout::dense};
#pragma omp parallel for schedule(static) if (parallel_for(double(m) * m * n / 2))
        for (int j = 0; j < n; ++j) {
            T *column = B + std::ptrdiff_t(j) * ldb;
            if (alpha != T(1))
                for (int i = 0; i < m; ++i)
                    column[i] *= alpha;
            trsv_builtin(tri, trans, d, v(column, m, 1));
        }
    } else {
        const triangle<const T> tri{A, lda, 0, n, uplo, layout::dense};
        const op transposed = trans == op::n ? op::t : trans == op::t ? op::n : op::conj;
#pragma omp parallel for schedule(static) if (parallel_for(double(m) * n * n / 2))
        for (int i = 0; i < m; ++i) {
            const vec<T> row{B + i, n, ldb};
            if (alpha != T(1))
                for (int j = 0; j < n; ++j)
                    row[j] *= alpha;
            trsv_builtin(tri, transposed, d, row);
        }
    }
}

template <typename T>
status trsm(const context &c, side sd, fill uplo, op trans, diag d, int m, int n, scalar<T> alpha, const T *A,
            int lda, T *B, int ldb)
{
    if (alpha.missing)
        return status::invalid_value;
    if (status s = check_triangular_matrix(sd, uplo, trans, d, m, n, lda, ldb); s != status::success)
        return s;
    return run(c, [=] {
        if (m == 0 || n == 0)
            return;
        const T a = alpha.get();
        using F = void(int, int, int, int, int, int, int, cb_value<T>, cb_in<T>, int, cb_out<T>, int);
        if (auto f = cblas_function<F, T, "", "trsm">()) {
            f(col_major, cb(sd), cb(uplo), cb(trans), cb(d), m, n, value_arg(a), A, lda, B, ldb);
            return;
        }
        trsm_builtin(sd, uplo, trans, d, m, n, a, A, lda, B, ldb);
    });
}

template <typename T>
status trsm_batched(const context &c, side sd, fill uplo, op trans, diag d, int m, int n, scalar<T> alpha,
                    const T *const A[], int lda, T *const B[], int ldb, int batch)
{
    if (alpha.missing)
        return status::invalid_value;
    if (status s = check_triangular_matrix(sd, uplo, trans, d, m, n, lda, ldb); s != status::success)
        return s;
    if (batch < 0)
        return status::invalid_size;
    return run(c, [=] {
        if (m == 0 || n == 0)
            return;
        const T a = alpha.get();
#pragma omp parallel for schedule(dynamic) if (parallel_for(double(m) * m * n * batch))
        for (int i = 0; i < batch; ++i)
            trsm_builtin(sd, uplo, trans, d, m, n, a, A[i], lda, B[i], ldb);
    });
}

//! C = alpha op(A) + beta op(B); C may be A (op(A) = A, lda = ldc) or B
template <typename T>
status geam(const context &c, op ta, op tb, int m, int n, scalar<T> alpha, const T *A, int lda, scalar<T> beta,
            const T *B, int ldb, T *C, int ldc)
{
    if (!valid(ta) || !valid(tb) || alpha.missing || beta.missing)
        return status::invalid_value;
    if (m < 0 || n < 0 || lda < max1(ta == op::n ? m : n) || ldb < max1(tb == op::n ? m : n) || ldc < max1(m))
        return status::invalid_size;
    if ((C == A && (ta != op::n || lda != ldc)) || (C == B && (tb != op::n || ldb != ldc)))
        return status::invalid_value;
    return run(c, [=] {
        const T a = alpha.get();
        const T b = beta.get();
#pragma omp parallel for schedule(static) if (parallel_for(double(m) * n))
        for (int j = 0; j < n; ++j) {
            for (int i = 0; i < m; ++i) {
                const T x = a == T(0) ? T(0) : a * op_at(A, lda, ta, i, j);
                const T y = b == T(0) ? T(0) : b * op_at(B, ldb, tb, i, j);
                C[i + std::ptrdiff_t(j) * ldc] = x + y;
            }
        }
    });
}

//! C = A diag(x) (right) or diag(x) A (left)
template <typename T>
status dgmm(const context &c, side mode, int m, int n, const T *A, int lda, const T *x, int incx, T *C, int ldc)
{
    if (!valid(mode))
        return status::invalid_value;
    if (m < 0 || n < 0 || lda < max1(m) || ldc < max1(m))
        return status::invalid_size;
    return run(c, [=] {
        const auto X = v(x, mode == side::left ? m : n, incx);
#pragma omp parallel for schedule(static) if (parallel_for(double(m) * n))
        for (int j = 0; j < n; ++j)
            for (int i = 0; i < m; ++i)
                C[i + std::ptrdiff_t(j) * ldc] = A[i + std::ptrdiff_t(j) * lda] * (mode == side::left ? X[i] : X[j]);
    });
}

