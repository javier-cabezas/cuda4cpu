using half = ::__half;

//! The type a product computes in: float (16F and 32F's kinds), double,
//! int32, or their complex counterparts when C is complex
enum class compute { f32, f64, i32, invalid };

inline compute compute_of(int type)
{
    switch (type) {
    case CUBLAS_COMPUTE_16F:
    case CUBLAS_COMPUTE_16F_PEDANTIC:
    case CUBLAS_COMPUTE_32F:
    case CUBLAS_COMPUTE_32F_PEDANTIC:
    case CUBLAS_COMPUTE_32F_FAST_16F:
    case CUBLAS_COMPUTE_32F_FAST_16BF:
    case CUBLAS_COMPUTE_32F_FAST_TF32:
    case CUDA_R_16F: // cuBLAS 10's computeType, a cudaDataType
    case CUDA_R_32F:
    case CUDA_C_32F: return compute::f32;
    case CUBLAS_COMPUTE_64F:
    case CUBLAS_COMPUTE_64F_PEDANTIC:
    case CUDA_R_64F:
    case CUDA_C_64F: return compute::f64;
    case CUBLAS_COMPUTE_32I:
    case CUBLAS_COMPUTE_32I_PEDANTIC:
    case CUDA_R_32I: return compute::i32;
    }
    return compute::invalid;
}

inline bool is_half_compute(int type)
{
    return type == CUBLAS_COMPUTE_16F || type == CUBLAS_COMPUTE_16F_PEDANTIC || type == CUDA_R_16F;
}

inline bool complex_type(cudaDataType t) { return t == CUDA_C_32F || t == CUDA_C_64F; }

inline bool loadable(cudaDataType t)
{
    switch (t) {
    case CUDA_R_16F:
    case CUDA_R_16BF:
    case CUDA_R_32F:
    case CUDA_R_64F:
    case CUDA_R_8I:
    case CUDA_R_8U:
    case CUDA_R_32I:
    case CUDA_C_32F:
    case CUDA_C_64F: return true;
    default: return false;
    }
}

inline bool storable(cudaDataType t)
{
    return loadable(t) && t != CUDA_R_8U;
}

//! Element i of an array of type t, as T
template <typename T>
T load(const void *p, cudaDataType t, std::ptrdiff_t i)
{
    auto real = [&]() -> double {
        switch (t) {
        case CUDA_R_16F: return __half2float(static_cast<const half *>(p)[i]);
        case CUDA_R_16BF: return __bfloat162float(static_cast<const __nv_bfloat16 *>(p)[i]);
        case CUDA_R_32F: return static_cast<const float *>(p)[i];
        case CUDA_R_64F: return static_cast<const double *>(p)[i];
        case CUDA_R_8I: return static_cast<const int8_t *>(p)[i];
        case CUDA_R_8U: return static_cast<const uint8_t *>(p)[i];
        case CUDA_R_32I: return static_cast<const int32_t *>(p)[i];
        default: return 0;
        }
    };
    if (t == CUDA_C_32F || t == CUDA_C_64F) {
        const std::complex<double> z = t == CUDA_C_32F ? std::complex<double>(static_cast<const cf *>(p)[i])
                                                       : static_cast<const cd *>(p)[i];
        if constexpr (is_complex<T>)
            return T(z);
        else
            return T(z.real());
    }
    return T(real_t<T>(real()));
}

//! Stores value as element i of an array of type t: rounded to nearest, and
//! integers saturated
template <typename T>
void store(void *p, cudaDataType t, std::ptrdiff_t i, T value)
{
    auto saturate = [](double x, double lo, double hi) { return std::nearbyint(std::clamp(x, lo, hi)); };
    double re;
    if constexpr (is_complex<T>)
        re = value.real();
    else
        re = double(value);
    switch (t) {
    case CUDA_R_16F: static_cast<half *>(p)[i] = __float2half_rn(float(re)); break;
    case CUDA_R_16BF: static_cast<__nv_bfloat16 *>(p)[i] = __float2bfloat16_rn(float(re)); break;
    case CUDA_R_32F: static_cast<float *>(p)[i] = float(re); break;
    case CUDA_R_64F: static_cast<double *>(p)[i] = re; break;
    case CUDA_R_8I: static_cast<int8_t *>(p)[i] = int8_t(saturate(re, -128, 127)); break;
    case CUDA_R_32I: static_cast<int32_t *>(p)[i] = int32_t(saturate(re, -2147483648.0, 2147483647.0)); break;
    case CUDA_C_32F: static_cast<cf *>(p)[i] = cf(std::complex<double>(value)); break;
    case CUDA_C_64F: static_cast<cd *>(p)[i] = cd(std::complex<double>(value)); break;
    default: break;
    }
}

//! A matrix of type t (rows x cols, with leading dimension ld) as a dense
//! array of T
template <typename T>
std::vector<T> load_matrix(const void *p, cudaDataType t, int rows, int cols, int ld)
{
    std::vector<T> out(std::size_t(rows) * cols);
    for (int j = 0; j < cols; ++j)
        for (int i = 0; i < rows; ++i)
            out[i + std::size_t(j) * rows] = load<T>(p, t, i + std::ptrdiff_t(j) * ld);
    return out;
}

//! One product of the given types, computed in T: the operands converted
//! to T, unless they are T already
template <typename T>
void gemm_ex_one(op ta, op tb, int m, int n, int k, T alpha, const void *A, cudaDataType at, int lda, const void *B,
                 cudaDataType bt, int ldb, T beta, void *C, cudaDataType ct, int ldc, bool parallel)
{
    if (m == 0 || n == 0)
        return;
    constexpr cudaDataType native = std::is_same_v<T, float>    ? CUDA_R_32F
                                    : std::is_same_v<T, double> ? CUDA_R_64F
                                    : std::is_same_v<T, cf>     ? CUDA_C_32F
                                    : std::is_same_v<T, cd>     ? CUDA_C_64F
                                                                : CUDA_R_32I;
    if (at == native && bt == native && ct == native) {
        gemm_one(ta, tb, m, n, k, alpha, static_cast<const T *>(A), lda, static_cast<const T *>(B), ldb, beta,
                 static_cast<T *>(C), ldc, parallel);
        return;
    }
    const int ar = ta == op::n ? m : k, ac = ta == op::n ? k : m;
    const int br = tb == op::n ? k : n, bc = tb == op::n ? n : k;
    const std::vector<T> a = load_matrix<T>(A, at, ar, ac, lda);
    const std::vector<T> b = load_matrix<T>(B, bt, br, bc, ldb);
    std::vector<T> c = beta == T(0) ? std::vector<T>(std::size_t(m) * n) : load_matrix<T>(C, ct, m, n, ldc);
    gemm_one(ta, tb, m, n, k, alpha, a.data(), max1(ar), b.data(), max1(br), beta, c.data(), m, parallel);
    for (int j = 0; j < n; ++j)
        for (int i = 0; i < m; ++i)
            store(C, ct, i + std::ptrdiff_t(j) * ldc, c[i + std::size_t(j) * m]);
}

//! Reads alpha or beta: their type is the computation's (__half for 16F)
template <typename T>
T load_scalar(const void *p, int compute_type)
{
    if constexpr (std::is_same_v<T, float>)
        if (is_half_compute(compute_type))
            return __half2float(*static_cast<const half *>(p));
    return *static_cast<const T *>(p);
}

//! The batch's products: A, B and C give each one's pointers
template <typename T, typename Ptrs>
status gemm_ex_typed(const context &c, op ta, op tb, int m, int n, int k, const void *alpha, cudaDataType at,
                     int lda, cudaDataType bt, int ldb, const void *beta, cudaDataType ct, int ldc, int batch,
                     int compute_type, Ptrs ptrs)
{
    // Scalars: with the host's pointers, read now; else when the product runs
    const bool now = !c.device_pointers;
    const T a0 = now ? load_scalar<T>(alpha, compute_type) : T();
    const T b0 = now ? load_scalar<T>(beta, compute_type) : T();
    return run(c, [=] {
        const T a = now ? a0 : load_scalar<T>(alpha, compute_type);
        const T b = now ? b0 : load_scalar<T>(beta, compute_type);
        each_product<T>(batch, m, n, k, [&](int i, bool parallel) {
            const auto [A, B, C] = ptrs(i);
            gemm_ex_one(ta, tb, m, n, k, a, A, at, lda, B, bt, ldb, b, C, ct, ldc, parallel);
        });
    });
}

template <typename Ptrs>
status gemm_ex(const context &c, op ta, op tb, int m, int n, int k, const void *alpha, cudaDataType at, int lda,
               cudaDataType bt, int ldb, const void *beta, cudaDataType ct, int ldc, int batch, int compute_type,
               Ptrs ptrs)
{
    if (alpha == nullptr || beta == nullptr)
        return status::invalid_value;
    if (status s = check_gemm(ta, tb, m, n, k, lda, ldb, ldc); s != status::success)
        return s;
    if (batch < 0)
        return status::invalid_size;
    const compute kind = compute_of(compute_type);
    if (kind == compute::invalid || !loadable(at) || !loadable(bt) || !storable(ct) ||
        complex_type(at) != complex_type(ct) || complex_type(bt) != complex_type(ct) ||
        (kind == compute::i32 && complex_type(ct)))
        return status::not_supported;
    const bool cx = complex_type(ct);
    switch (kind) {
    case compute::f32:
        return cx ? gemm_ex_typed<cf>(c, ta, tb, m, n, k, alpha, at, lda, bt, ldb, beta, ct, ldc, batch, compute_type, ptrs)
                  : gemm_ex_typed<float>(c, ta, tb, m, n, k, alpha, at, lda, bt, ldb, beta, ct, ldc, batch, compute_type,
                                         ptrs);
    case compute::f64:
        return cx ? gemm_ex_typed<cd>(c, ta, tb, m, n, k, alpha, at, lda, bt, ldb, beta, ct, ldc, batch, compute_type, ptrs)
                  : gemm_ex_typed<double>(c, ta, tb, m, n, k, alpha, at, lda, bt, ldb, beta, ct, ldc, batch,
                                          compute_type, ptrs);
    case compute::i32:
        return gemm_ex_typed<int32_t>(c, ta, tb, m, n, k, alpha, at, lda, bt, ldb, beta, ct, ldc, batch, compute_type,
                                      ptrs);
    case compute::invalid: break;
    }
    return status::not_supported;
}

