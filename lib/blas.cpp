cublasStatus_t cublasGemmStridedBatchedEx(cublasHandle_t handle, cublasOperation_t transa, cublasOperation_t transb,
                                          int m, int n, int k, const void *alpha, const void *A, cudaDataType Atype,
                                          int lda, long long int strideA, const void *B, cudaDataType Btype, int ldb,
                                          long long int strideB, const void *beta, void *C, cudaDataType Ctype,
                                          int ldc, long long int strideC, int batchCount,
                                          cublasComputeType_t computeType, cublasGemmAlgo_t)
{
    CUDA4CPU_BLAS_CONTEXT(cublasStatus_t, handle);
    const auto size = [](cudaDataType t) -> long long {
        switch (t) {
        case CUDA_R_16F:
        case CUDA_R_16BF: return 2;
        case CUDA_R_8I:
        case CUDA_R_8U: return 1;
        case CUDA_R_64F:
        case CUDA_C_32F: return 8;
        case CUDA_C_64F: return 16;
        default: return 4;
        }
    };
    const long long sa = strideA * size(Atype), sb = strideB * size(Btype), sc = strideC * size(Ctype);
    return blas::api_status<cublasStatus_t>(blas::gemm_ex(
        *context, blas::arg(transa), blas::arg(transb), m, n, k, alpha, Atype, lda, Btype, ldb, beta, Ctype, ldc,
        batchCount, computeType, [=](int i) {
            return blas::product_pointers{static_cast<const char *>(A) + i * sa, static_cast<const char *>(B) + i * sb,
                                          static_cast<char *>(C) + i * sc};
        }));
}

