//! A += alpha x y^T + alpha y x^T (two), or alpha x x^T, on the stored
//! triangle; hermitian: A += alpha x y^H + conj(alpha) y x^H, or alpha x x^H
//! with alpha real, and a real diagonal
template <typename T>
void rank_update_builtin(triangle<T> A, bool herm, bool two, T alpha, const T *x, int incx, const T *y, int incy)
{
    const int n = A.n;
    const auto X = v(x, n, incx);
    const auto Y = v(y != nullptr ? y : x, n, y != nullptr ? incy : incx);
    for (int j = 0; j < n; ++j) {
        const int i0 = A.uplo == fill::upper ? 0 : j;
        const int i1 = A.uplo == fill::upper ? j + 1 : n;
        for (int i = i0; i < i1; ++i) {
            T update = alpha * X[i] * conj_if(two ? Y[j] : X[j], herm);
            if (two)
                update += conj_if(alpha, herm) * Y[i] * conj_if(X[j], herm);
            T &e = A.ref(i, j);
            e += update;
            if (herm && i == j)
                e = real_part(e);
        }
    }
}

template <typename T, typename A>
status syr_of(const context &c, fill uplo, int n, scalar<A> alpha, const T *x, int incx, const T *y, int incy,
              T *a, int lda, layout lay, bool herm)
{
    if (!valid(uplo) || alpha.missing)
        return status::invalid_value;
    if (n < 0 || incx == 0 || (y != nullptr && incy == 0) || (lay == layout::dense && lda < max1(n)))
        return status::invalid_size;
    return run(c, [=] {
        if (n == 0)
            return;
        const A al = alpha.get();
        if (lay == layout::dense && (herm || !is_complex<T>)) {
            if (y == nullptr) {
                using R = real_t<T>;
                using F = void(int, int, int, std::conditional_t<is_complex<T>, R, T>, cb_in<T>, int, cb_out<T>, int);
                F *f = herm ? cblas_function<F, T, "", "her">() : cblas_function<F, T, "", "syr">();
                if (f != nullptr) {
                    f(col_major, cb(uplo), n, std::real(al), x, incx, a, lda);
                    return;
                }
            } else if constexpr (std::is_same_v<A, T>) {
                using F = void(int, int, int, cb_value<T>, cb_in<T>, int, cb_in<T>, int, cb_out<T>, int);
                F *f = herm ? cblas_function<F, T, "", "her2">() : cblas_function<F, T, "", "syr2">();
                if (f != nullptr) {
                    f(col_major, cb(uplo), n, value_arg(al), x, incx, y, incy, a, lda);
                    return;
                }
            }
        }
        rank_update_builtin(triangle<T>{a, lda, 0, n, uplo, lay}, herm, y != nullptr, T(al), x, incx, y, incy);
    });
}

