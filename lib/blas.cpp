using cf = std::complex<float>;
using cd = std::complex<double>;

template <typename T> struct real_of { using type = T; };
template <typename T> struct real_of<std::complex<T>> { using type = T; };
template <typename T> using real_t = typename real_of<T>::type;
template <typename T> constexpr bool is_complex = !std::is_same_v<T, real_t<T>>;

template <typename T>
T conj_if(T x, bool conjugate)
{
    if constexpr (is_complex<T>)
        return conjugate ? std::conj(x) : x;
    else
        return x;
}

//! |re| + |im|, the BLAS's absolute value of complex numbers (asum, iamax)
template <typename T>
real_t<T> abs1(T x)
{
    if constexpr (is_complex<T>)
        return std::abs(x.real()) + std::abs(x.imag());
    else
        return std::abs(x);
}

template <typename T>
T real_part(T x)
{
    if constexpr (is_complex<T>)
        return T(x.real());
    else
        return x;
}

// Statuses, and each API's

enum class status { success, not_initialized, alloc_failed, invalid_value, invalid_size, not_supported,
                    execution_failed, internal_error };

template <typename S> S api_status(status s);

template <>
cublasStatus_t api_status(status s)
{
    switch (s) {
    case status::success: return CUBLAS_STATUS_SUCCESS;
    case status::not_initialized: return CUBLAS_STATUS_NOT_INITIALIZED;
    case status::alloc_failed: return CUBLAS_STATUS_ALLOC_FAILED;
    case status::invalid_value:
    case status::invalid_size: return CUBLAS_STATUS_INVALID_VALUE;
    case status::not_supported: return CUBLAS_STATUS_NOT_SUPPORTED;
    case status::execution_failed: return CUBLAS_STATUS_EXECUTION_FAILED;
    case status::internal_error: break;
    }
    return CUBLAS_STATUS_INTERNAL_ERROR;
}

template <>
hipblasStatus_t api_status(status s)
{
    switch (s) {
    case status::success: return HIPBLAS_STATUS_SUCCESS;
    case status::not_initialized: return HIPBLAS_STATUS_NOT_INITIALIZED;
    case status::alloc_failed: return HIPBLAS_STATUS_ALLOC_FAILED;
    case status::invalid_value:
    case status::invalid_size: return HIPBLAS_STATUS_INVALID_VALUE;
    case status::not_supported: return HIPBLAS_STATUS_NOT_SUPPORTED;
    case status::execution_failed: return HIPBLAS_STATUS_EXECUTION_FAILED;
    case status::internal_error: break;
    }
    return HIPBLAS_STATUS_INTERNAL_ERROR;
}

template <>
rocblas_status api_status(status s)
{
    switch (s) {
    case status::success: return rocblas_status_success;
    case status::not_initialized: return rocblas_status_invalid_handle;
    case status::alloc_failed: return rocblas_status_memory_error;
    case status::invalid_value: return rocblas_status_invalid_value;
    case status::invalid_size: return rocblas_status_invalid_size;
    case status::not_supported: return rocblas_status_not_implemented;
    case status::execution_failed:
    case status::internal_error: break;
    }
    return rocblas_status_internal_error;
}

// Enumerations: conj is cuBLAS's CUBLAS_OP_CONJG, and the conjugate without
// the transpose that solving X op(A) = B needs (trsm's right side)

enum class op { n, t, c, conj, invalid };
enum class fill { upper, lower, full, invalid };
enum class diag { non_unit, unit, invalid };
enum class side { left, right, invalid };

inline op arg(cublasOperation_t v)
{
    switch (v) {
    case CUBLAS_OP_N: return op::n;
    case CUBLAS_OP_T: return op::t;
    case CUBLAS_OP_C: return op::c;
    case CUBLAS_OP_CONJG: return op::conj;
    }
    return op::invalid;
}

inline fill arg(cublasFillMode_t v)
{
    switch (v) {
    case CUBLAS_FILL_MODE_UPPER: return fill::upper;
    case CUBLAS_FILL_MODE_LOWER: return fill::lower;
    case CUBLAS_FILL_MODE_FULL: return fill::full;
    }
    return fill::invalid;
}

inline diag arg(cublasDiagType_t v)
{
    return v == CUBLAS_DIAG_NON_UNIT ? diag::non_unit : v == CUBLAS_DIAG_UNIT ? diag::unit : diag::invalid;
}

inline side arg(cublasSideMode_t v)
{
    return v == CUBLAS_SIDE_LEFT ? side::left : v == CUBLAS_SIDE_RIGHT ? side::right : side::invalid;
}

//! hipBLAS's and rocBLAS's enumerations have the same values (the
//! reference CBLAS's)
inline op amd_op(int v) { return v == 111 ? op::n : v == 112 ? op::t : v == 113 ? op::c : op::invalid; }
inline fill amd_fill(int v)
{
    return v == 121 ? fill::upper : v == 122 ? fill::lower : v == 123 ? fill::full : fill::invalid;
}
inline diag amd_diag(int v) { return v == 131 ? diag::non_unit : v == 132 ? diag::unit : diag::invalid; }
inline side amd_side(int v) { return v == 141 ? side::left : v == 142 ? side::right : side::invalid; }

inline op arg(hipblasOperation_t v) { return amd_op(v); }
inline fill arg(hipblasFillMode_t v) { return amd_fill(v); }
inline diag arg(hipblasDiagType_t v) { return amd_diag(v); }
inline side arg(hipblasSideMode_t v) { return amd_side(v); }
inline op arg(rocblas_operation v) { return amd_op(v); }
inline fill arg(rocblas_fill v) { return amd_fill(v); }
inline diag arg(rocblas_diagonal v) { return amd_diag(v); }
inline side arg(rocblas_side v) { return amd_side(v); }

// Pointers: the APIs' complex types are laid out as std::complex

template <typename X> struct core { using type = X; };
template <> struct core<float2> { using type = cf; };
template <> struct core<double2> { using type = cd; };
template <> struct core<rocblas_float_complex> { using type = cf; };
template <> struct core<rocblas_double_complex> { using type = cd; };
template <typename X> struct core<const X> { using type = const typename core<X>::type; };
template <typename X> struct core<X *> { using type = typename core<X>::type *; };

static_assert(sizeof(float2) == sizeof(cf) && alignof(float2) >= alignof(cf));
static_assert(sizeof(double2) == sizeof(cd) && alignof(double2) >= alignof(cd));
static_assert(sizeof(rocblas_float_complex) == sizeof(cf) && sizeof(rocblas_double_complex) == sizeof(cd));

template <typename X>
typename core<X *>::type ptr(X *p)
{
    return reinterpret_cast<typename core<X *>::type>(p);
}

// A handle's state, which every API's handle points to

struct context {
    cudaStream_t stream = nullptr;
    bool device_pointers = false;
    int math_mode = 0;
    int atomics = 0;
    int sm_count_target = 0;
};

template <typename H>
context *context_of(H handle)
{
    return reinterpret_cast<context *>(handle);
}

#define CUDA4CPU_BLAS_CONTEXT(status_type, handle)                                                                  \
    blas::context *context = blas::context_of(handle);                                                              \
    if (context == nullptr)                                                                                         \
        return blas::api_status<status_type>(blas::status::not_initialized)

//! A scalar argument: with the host's pointers, its value when the routine
//! is called; with the device's, the pointer, read when the routine runs
//! (in a graph, the value the graph's earlier nodes left)
template <typename T>
struct scalar {
    T value{};
    const T *pointer = nullptr;
    bool missing = false;

    T get() const { return pointer != nullptr ? *pointer : value; }
};

template <typename X>
scalar<std::remove_const_t<typename core<X>::type>> scalar_in(const context &c, X *p)
{
    using T = std::remove_const_t<typename core<X>::type>;
    scalar<T> s;
    if (p == nullptr)
        s.missing = true;
    else if (c.device_pointers)
        s.pointer = ptr(p);
    else
        s.value = *ptr(p);
    return s;
}

