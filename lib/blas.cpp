//! C = alpha A B + beta C (left) or alpha B A + beta C (right), A symmetric
//! or hermitian
template <typename T>
status symm_of(const context &c, side sd, fill uplo, int m, int n, scalar<T> alpha, const T *A, int lda, const T *B,
               int ldb, scalar<T> beta, T *C, int ldc, bool herm)
{
    if (!valid(sd) || !valid(uplo) || alpha.missing || beta.missing)
        return status::invalid_value;
    const int ka = sd == side::left ? m : n;
    if (m < 0 || n < 0 || lda < max1(ka) || ldb < max1(m) || ldc < max1(m))
        return status::invalid_size;
    return run(c, [=] {
        if (m == 0 || n == 0)
            return;
        const T a = alpha.get();
        const T b = beta.get();
        using F = void(int, int, int, int, int, cb_value<T>, cb_in<T>, int, cb_in<T>, int, cb_value<T>, cb_out<T>, int);
        if (auto f = herm ? cblas_function<F, T, "", "hemm">() : cblas_function<F, T, "", "symm">()) {
            f(col_major, cb(sd), cb(uplo), m, n, value_arg(a), A, lda, B, ldb, value_arg(b), C, ldc);
            return;
        }
        const triangle<const T> S{A, lda, 0, ka, uplo, layout::dense};
#pragma omp parallel for schedule(static) if (parallel_for(double(m) * n * ka))
        for (int j = 0; j < n; ++j) {
            for (int i = 0; i < m; ++i) {
                T s = 0;
                if (sd == side::left)
                    for (int l = 0; l < m; ++l)
                        s += S.sym(i, l, herm) * B[l + std::ptrdiff_t(j) * ldb];
                else
                    for (int l = 0; l < n; ++l)
                        s += B[i + std::ptrdiff_t(l) * ldb] * S.sym(l, j, herm);
                T &e = C[i + std::ptrdiff_t(j) * ldc];
                e = a * s + (b == T(0) ? T(0) : b * e);
            }
        }
    });
}

template <typename T>
status symm(const context &c, side sd, fill uplo, int m, int n, scalar<T> alpha, const T *A, int lda, const T *B,
            int ldb, scalar<T> beta, T *C, int ldc)
{
    return symm_of(c, sd, uplo, m, n, alpha, A, lda, B, ldb, beta, C, ldc, false);
}

template <typename T>
status hemm(const context &c, side sd, fill uplo, int m, int n, scalar<T> alpha, const T *A, int lda, const T *B,
            int ldb, scalar<T> beta, T *C, int ldc)
{
    return symm_of(c, sd, uplo, m, n, alpha, A, lda, B, ldb, beta, C, ldc, true);
}

enum class rank_kind { k, two_k, kx };

//! The stored triangle of C = alpha P Q^T + beta C (syrk: Q = P, syrkx),
//! or alpha P Q^T + alpha Q P^T + beta C (syr2k), with P = op(A) and
//! Q = op(B); hermitian (herk, herkx, her2k): Q^H, conj(alpha) on the second
//! term, and a real diagonal
template <typename T>
void rank_k_builtin(fill uplo, op trans, int n, int k, T alpha, const T *A, int lda, const T *B, int ldb, T beta,
                    T *C, int ldc, bool herm, rank_kind kind)
{
    auto P = [&](int i, int l) { return trans == op::n ? A[i + std::ptrdiff_t(l) * lda]
                                                       : conj_if(A[l + std::ptrdiff_t(i) * lda], trans == op::c); };
    auto Q = [&](int i, int l) { return trans == op::n ? B[i + std::ptrdiff_t(l) * ldb]
                                                       : conj_if(B[l + std::ptrdiff_t(i) * ldb], trans == op::c); };
#pragma omp parallel for schedule(dynamic, 8) if (parallel_for(double(n) * n * std::max(k, 1) / 2))
    for (int j = 0; j < n; ++j) {
        const int i0 = uplo == fill::upper ? 0 : j;
        const int i1 = uplo == fill::upper ? j + 1 : n;
        for (int i = i0; i < i1; ++i) {
            T s = 0;
            T s2 = 0;
            if (alpha != T(0)) {
                for (int l = 0; l < k; ++l) {
                    s += P(i, l) * conj_if(Q(j, l), herm);
                    if (kind == rank_kind::two_k)
                        s2 += Q(i, l) * conj_if(P(j, l), herm);
                }
            }
            T value = alpha * s;
            if (kind == rank_kind::two_k)
                value += conj_if(alpha, herm) * s2;
            T &e = C[i + std::ptrdiff_t(j) * ldc];
            e = value + (beta == T(0) ? T(0) : beta * e);
            if (herm && i == j)
                e = real_part(e);
        }
    }
}

template <typename T, typename A, typename Bt>
status rank_k_of(const context &c, fill uplo, op trans, int n, int k, scalar<A> alpha, const T *a, int lda,
                 const T *b, int ldb, scalar<Bt> beta, T *C, int ldc, bool herm, rank_kind kind)
{
    // Real types take any op (op::c is op::t); complex ones N or T
    // (symmetric) or N or C (hermitian)
    const bool trans_ok = !is_complex<T> ? valid(trans) : herm ? trans == op::n || trans == op::c
                                                                : trans == op::n || trans == op::t;
    if (!valid(uplo) || !trans_ok || alpha.missing || beta.missing)
        return status::invalid_value;
    const int rows = trans == op::n ? n : k;
    if (n < 0 || k < 0 || lda < max1(rows) || (kind != rank_kind::k && ldb < max1(rows)) || ldc < max1(n))
        return status::invalid_size;
    return run(c, [=] {
        if (n == 0)
            return;
        const A al = alpha.get();
        const Bt be = beta.get();
        const op t = !is_complex<T> && trans == op::c ? op::t : trans;
        if (kind == rank_kind::k) {
            using V = std::conditional_t<std::is_same_v<A, T>, cb_value<T>, A>;
            using F = void(int, int, int, int, int, V, cb_in<T>, int, std::conditional_t<std::is_same_v<Bt, T>, cb_value<T>, Bt>,
                           cb_out<T>, int);
            if (auto f = herm ? cblas_function<F, T, "", "herk">() : cblas_function<F, T, "", "syrk">()) {
                if constexpr (std::is_same_v<A, T>)
                    f(col_major, cb(uplo), cb(t), n, k, value_arg(al), a, lda, value_arg(be), C, ldc);
                else
                    f(col_major, cb(uplo), cb(t), n, k, al, a, lda, be, C, ldc);
                return;
            }
        } else if (kind == rank_kind::two_k) {
            using W = std::conditional_t<std::is_same_v<Bt, T>, cb_value<T>, Bt>;
            using F = void(int, int, int, int, int, cb_value<T>, cb_in<T>, int, cb_in<T>, int, W, cb_out<T>, int);
            if (auto f = herm ? cblas_function<F, T, "", "her2k">() : cblas_function<F, T, "", "syr2k">()) {
                if constexpr (std::is_same_v<Bt, T>)
                    f(col_major, cb(uplo), cb(t), n, k, value_arg(T(al)), a, lda, b, ldb, value_arg(be), C, ldc);
                else
                    f(col_major, cb(uplo), cb(t), n, k, value_arg(T(al)), a, lda, b, ldb, be, C, ldc);
                return;
            }
        }
        rank_k_builtin(uplo, t, n, k, T(al), a, lda, kind == rank_kind::k ? a : b, kind == rank_kind::k ? lda : ldb,
                       T(be), C, ldc, herm, kind);
    });
}

