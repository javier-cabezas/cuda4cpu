// Level 1

template <typename T>
status iamax_or_min(const context &c, int n, const T *x, int incx, int *result, bool max)
{
    if (result == nullptr)
        return status::invalid_value;
    return run(c, [=] {
        int best = 0;
        if (n > 0 && incx > 0) {
            if (auto f = cblas_function<std::size_t(int, cb_in<T>, int), T, "i", "amax">(); f != nullptr && max) {
                best = int(f(n, x, incx)) + 1;
            } else {
                real_t<T> value = abs1(x[0]);
                best = 1;
                for (int i = 1; i < n; ++i) {
                    const real_t<T> a = abs1(x[std::ptrdiff_t(i) * incx]);
                    if (max ? a > value : a < value) {
                        value = a;
                        best = i + 1;
                    }
                }
            }
        }
        *result = best;
    });
}

template <typename T>
status iamax(const context &c, int n, const T *x, int incx, int *result)
{
    return iamax_or_min(c, n, x, incx, result, true);
}

template <typename T>
status iamin(const context &c, int n, const T *x, int incx, int *result)
{
    return iamax_or_min(c, n, x, incx, result, false);
}

// cblas_scasum and cblas_dzasum, cblas_scnrm2 and cblas_dznrm2: the real
// type's letter before the complex one's
template <typename F, typename T, fixed_string Suffix>
F *cblas_real_complex()
{
    if constexpr (std::is_same_v<T, cf>)
        return cblas_function<F, cf, "s", Suffix>();
    else if constexpr (std::is_same_v<T, cd>)
        return cblas_function<F, cd, "d", Suffix>();
    else
        return cblas_function<F, T, "", Suffix>();
}

template <typename T>
status asum(const context &c, int n, const T *x, int incx, real_t<T> *result)
{
    if (result == nullptr)
        return status::invalid_value;
    return run(c, [=] {
        real_t<T> sum = 0;
        if (n > 0 && incx > 0) {
            if (auto f = cblas_real_complex<real_t<T>(int, cb_in<T>, int), T, "asum">())
                sum = f(n, x, incx);
            else
                for (int i = 0; i < n; ++i)
                    sum += abs1(x[std::ptrdiff_t(i) * incx]);
        }
        *result = sum;
    });
}

template <typename T>
status axpy(const context &c, int n, scalar<T> alpha, const T *x, int incx, T *y, int incy)
{
    if (alpha.missing)
        return status::invalid_value;
    return run(c, [=] {
        if (n <= 0)
            return;
        const T a = alpha.get();
        if (auto f = cblas_function<void(int, cb_value<T>, cb_in<T>, int, cb_out<T>, int), T, "", "axpy">()) {
            f(n, value_arg(a), x, incx, y, incy);
            return;
        }
        const auto X = v(x, n, incx);
        const auto Y = v(y, n, incy);
        for (int i = 0; i < n; ++i)
            Y[i] += a * X[i];
    });
}

template <typename T>
status copy(const context &c, int n, const T *x, int incx, T *y, int incy)
{
    return run(c, [=] {
        if (n <= 0)
            return;
        if (auto f = cblas_function<void(int, cb_in<T>, int, cb_out<T>, int), T, "", "copy">()) {
            f(n, x, incx, y, incy);
            return;
        }
        const auto X = v(x, n, incx);
        const auto Y = v(y, n, incy);
        for (int i = 0; i < n; ++i)
            Y[i] = X[i];
    });
}

template <typename T>
T dot_builtin(int n, const T *x, int incx, const T *y, int incy, bool conjugate)
{
    T sum = 0;
    const auto X = v(x, n, incx);
    const auto Y = v(y, n, incy);
    for (int i = 0; i < n; ++i)
        sum += conj_if(X[i], conjugate) * Y[i];
    return sum;
}

template <typename T>
status dot_of(const context &c, int n, const T *x, int incx, const T *y, int incy, T *result, bool conjugate)
{
    if (result == nullptr)
        return status::invalid_value;
    return run(c, [=] {
        T sum = 0;
        if (n > 0) {
            if constexpr (is_complex<T>) {
                using F = void(int, const void *, int, const void *, int, void *);
                F *f = conjugate ? cblas_function<F, T, "", "dotc_sub">() : cblas_function<F, T, "", "dotu_sub">();
                if (f != nullptr)
                    f(n, x, incx, y, incy, &sum);
                else
                    sum = dot_builtin(n, x, incx, y, incy, conjugate);
            } else if (auto f = cblas_function<T(int, const T *, int, const T *, int), T, "", "dot">()) {
                sum = f(n, x, incx, y, incy);
            } else {
                sum = dot_builtin(n, x, incx, y, incy, false);
            }
        }
        *result = sum;
    });
}

template <typename T>
status dot(const context &c, int n, const T *x, int incx, const T *y, int incy, T *result)
{
    return dot_of(c, n, x, incx, y, incy, result, false);
}

template <typename T>
status dotc(const context &c, int n, const T *x, int incx, const T *y, int incy, T *result)
{
    return dot_of(c, n, x, incx, y, incy, result, true);
}

//! The Euclidean norm, scaled as the reference BLAS's, so that the squares
//! neither overflow nor underflow
template <typename T>
real_t<T> nrm2_builtin(int n, const T *x, int incx)
{
    using R = real_t<T>;
    R scale = 0;
    R ssq = 1;
    auto add = [&](R value) {
        if (value != 0) {
            const R a = std::abs(value);
            if (scale < a) {
                ssq = 1 + ssq * (scale / a) * (scale / a);
                scale = a;
            } else {
                ssq += (a / scale) * (a / scale);
            }
        }
    };
    for (int i = 0; i < n; ++i) {
        const T e = x[std::ptrdiff_t(i) * incx];
        if constexpr (is_complex<T>) {
            add(e.real());
            add(e.imag());
        } else {
            add(e);
        }
    }
    return scale * std::sqrt(ssq);
}

template <typename T>
status nrm2(const context &c, int n, const T *x, int incx, real_t<T> *result)
{
    if (result == nullptr)
        return status::invalid_value;
    return run(c, [=] {
        real_t<T> norm = 0;
        if (n > 0 && incx > 0) {
            if (auto f = cblas_real_complex<real_t<T>(int, cb_in<T>, int), T, "nrm2">())
                norm = f(n, x, incx);
            else
                norm = nrm2_builtin(n, x, incx);
        }
        *result = norm;
    });
}

template <typename T, typename S>
status rot(const context &c, int n, T *x, int incx, T *y, int incy, scalar<real_t<T>> cs, scalar<S> sn)
{
    if (cs.missing || sn.missing)
        return status::invalid_value;
    return run(c, [=] {
        if (n <= 0)
            return;
        const real_t<T> cv = cs.get();
        const S sv = sn.get();
        if constexpr (!is_complex<T>) {
            if (auto f = cblas_function<void(int, T *, int, T *, int, T, T), T, "", "rot">()) {
                f(n, x, incx, y, incy, cv, sv);
                return;
            }
        }
        const auto X = v(x, n, incx);
        const auto Y = v(y, n, incy);
        for (int i = 0; i < n; ++i) {
            const T xi = X[i];
            const T yi = Y[i];
            X[i] = cv * xi + sv * yi;
            if constexpr (is_complex<S>)
                Y[i] = cv * yi - std::conj(sv) * xi;
            else
                Y[i] = cv * yi - sv * xi;
        }
    });
}

//! The Givens rotation that zeros b, as the reference BLAS's rotg
template <typename T>
status rotg(const context &c, T *a, T *b, real_t<T> *cs, T *sn)
{
    if (a == nullptr || b == nullptr || cs == nullptr || sn == nullptr)
        return status::invalid_value;
    return run(c, [=] {
        using R = real_t<T>;
        if constexpr (is_complex<T>) {
            const T ca = *a;
            const T cb_ = *b;
            if (std::abs(ca) == R(0)) {
                *cs = 0;
                *sn = 1;
                *a = cb_;
            } else {
                const R scale = std::abs(ca) + std::abs(cb_);
                const R norm = scale * std::sqrt(std::norm(ca / scale) + std::norm(cb_ / scale));
                const T alpha = ca / std::abs(ca);
                *cs = std::abs(ca) / norm;
                *sn = alpha * std::conj(cb_) / norm;
                *a = alpha * norm;
            }
        } else {
            const R av = *a;
            const R bv = *b;
            const R roe = std::abs(av) > std::abs(bv) ? av : bv;
            const R scale = std::abs(av) + std::abs(bv);
            if (scale == 0) {
                *cs = 1;
                *sn = 0;
                *a = 0;
                *b = 0;
                return;
            }
            R r = scale * std::sqrt((av / scale) * (av / scale) + (bv / scale) * (bv / scale));
            r = std::copysign(R(1), roe) * r;
            const R cv = av / r;
            const R sv = bv / r;
            R z = 1;
            if (std::abs(av) > std::abs(bv))
                z = sv;
            else if (cv != 0)
                z = 1 / cv;
            *cs = cv;
            *sn = sv;
            *a = r;
            *b = z;
        }
    });
}

//! The modified Givens transformation H: param is its flag (-2: identity,
//! -1: H in full, 0: h11 = h22 = 1, 1: h21 = -1 and h12 = 1) and h11, h21,
//! h12, h22
template <typename T>
status rotm(const context &c, int n, T *x, int incx, T *y, int incy, const T *param)
{
    if (param == nullptr)
        return status::invalid_value;
    return run(c, [=] {
        const T flag = param[0];
        if (n <= 0 || flag == T(-2))
            return;
        if (auto f = cblas_function<void(int, T *, int, T *, int, const T *), T, "", "rotm">()) {
            f(n, x, incx, y, incy, param);
            return;
        }
        T h11 = 1, h21 = -1, h12 = 1, h22 = 1;
        if (flag == T(-1)) {
            h11 = param[1];
            h21 = param[2];
            h12 = param[3];
            h22 = param[4];
        } else if (flag == T(0)) {
            h21 = param[2];
            h12 = param[3];
        } else {
            h11 = param[1];
            h22 = param[4];
        }
        const auto X = v(x, n, incx);
        const auto Y = v(y, n, incy);
        for (int i = 0; i < n; ++i) {
            const T w = X[i];
            const T z = Y[i];
            X[i] = h11 * w + h12 * z;
            Y[i] = h21 * w + h22 * z;
        }
    });
}

//! The modified Givens transformation that zeros the second component of
//! (sqrt(d1) x1, sqrt(d2) y1), as the reference BLAS's rotmg
template <typename T>
void rotmg_builtin(T *d1, T *d2, T *x1, T y1, T *param)
{
    constexpr T gam = 4096;
    constexpr T gamsq = gam * gam;
    constexpr T rgamsq = 1 / gamsq;
    T flag;
    T h11 = 0, h12 = 0, h21 = 0, h22 = 0;
    if (*d1 < 0) {
        flag = -1;
        *d1 = *d2 = *x1 = 0;
    } else {
        const T p2 = *d2 * y1;
        if (p2 == 0) {
            param[0] = -2;
            return;
        }
        const T p1 = *d1 * *x1;
        const T q2 = p2 * y1;
        const T q1 = p1 * *x1;
        if (std::abs(q1) > std::abs(q2)) {
            h21 = -y1 / *x1;
            h12 = p2 / p1;
            const T u = 1 - h12 * h21;
            if (u > 0) {
                flag = 0;
                *d1 /= u;
                *d2 /= u;
                *x1 *= u;
            } else {
                flag = -1;
                h11 = h12 = h21 = h22 = 0;
                *d1 = *d2 = *x1 = 0;
            }
        } else if (q2 < 0) {
            flag = -1;
            h11 = h12 = h21 = h22 = 0;
            *d1 = *d2 = *x1 = 0;
        } else {
            flag = 1;
            h11 = p1 / p2;
            h22 = *x1 / y1;
            const T u = 1 + h11 * h22;
            const T temp = *d2 / u;
            *d2 = *d1 / u;
            *d1 = temp;
            *x1 = y1 * u;
        }
        auto make_full = [&] {
            if (flag == 0) {
                h11 = 1;
                h22 = 1;
            } else if (flag == 1) {
                h21 = -1;
                h12 = 1;
            }
            flag = -1;
        };
        if (*d1 != 0) {
            while (*d1 <= rgamsq || *d1 >= gamsq) {
                make_full();
                if (*d1 <= rgamsq) {
                    *d1 *= gamsq;
                    *x1 /= gam;
                    h11 /= gam;
                    h12 /= gam;
                } else {
                    *d1 /= gamsq;
                    *x1 *= gam;
                    h11 *= gam;
                    h12 *= gam;
                }
            }
        }
        if (*d2 != 0) {
            while (std::abs(*d2) <= rgamsq || std::abs(*d2) >= gamsq) {
                make_full();
                if (std::abs(*d2) <= rgamsq) {
                    *d2 *= gamsq;
                    h21 /= gam;
                    h22 /= gam;
                } else {
                    *d2 /= gamsq;
                    h21 *= gam;
                    h22 *= gam;
                }
            }
        }
    }
    if (flag < 0) {
        param[1] = h11;
        param[2] = h21;
        param[3] = h12;
        param[4] = h22;
    } else if (flag == 0) {
        param[2] = h21;
        param[3] = h12;
    } else {
        param[1] = h11;
        param[4] = h22;
    }
    param[0] = flag;
}

template <typename T>
status rotmg(const context &c, T *d1, T *d2, T *x1, const T *y1, T *param)
{
    if (d1 == nullptr || d2 == nullptr || x1 == nullptr || y1 == nullptr || param == nullptr)
        return status::invalid_value;
    return run(c, [=] {
        if (auto f = cblas_function<void(T *, T *, T *, T, T *), T, "", "rotmg">())
            f(d1, d2, x1, *y1, param);
        else
            rotmg_builtin(d1, d2, x1, *y1, param);
    });
}

template <typename T, typename A>
status scal(const context &c, int n, scalar<A> alpha, T *x, int incx)
{
    if (alpha.missing)
        return status::invalid_value;
    return run(c, [=] {
        if (n <= 0 || incx <= 0)
            return;
        const A a = alpha.get();
        if constexpr (std::is_same_v<T, A>) {
            if (auto f = cblas_function<void(int, cb_value<T>, cb_out<T>, int), T, "", "scal">()) {
                f(n, value_arg(a), x, incx);
                return;
            }
        } else if constexpr (std::is_same_v<T, cf>) {
            if (auto f = cblas_function<void(int, float, void *, int), cf, "", "sscal">()) {
                f(n, a, x, incx);
                return;
            }
        } else {
            if (auto f = cblas_function<void(int, double, void *, int), cd, "", "dscal">()) {
                f(n, a, x, incx);
                return;
            }
        }
        for (int i = 0; i < n; ++i)
            x[std::ptrdiff_t(i) * incx] *= a;
    });
}

template <typename T>
status swap(const context &c, int n, T *x, int incx, T *y, int incy)
{
    return run(c, [=] {
        if (n <= 0)
            return;
        if (auto f = cblas_function<void(int, cb_out<T>, int, cb_out<T>, int), T, "", "swap">()) {
            f(n, x, incx, y, incy);
            return;
        }
        const auto X = v(x, n, incx);
        const auto Y = v(y, n, incy);
        for (int i = 0; i < n; ++i)
            std::swap(X[i], Y[i]);
    });
}

